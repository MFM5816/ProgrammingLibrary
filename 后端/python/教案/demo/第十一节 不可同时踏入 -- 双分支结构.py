##课堂练习2

"""
2. 青岛一日游的收费标准为：
  5 人以内（含 5 人）按散客标准，每人 300 元；
  超过 5 人，按照团体标准，每人 280 元。
  请根据输入的人数，输出旅游的费用
  输入样例：5
  输出样例：1500
"""
#使用 “如果....那么.... 否则....” 句式改写
people = int(input("num?"))
#如果输入的人数在5 人以内（含 5 人），那么每人300元
if people <= 5:
    print(people * 300)
#否则每人280元
else:
    print(people * 280)

##课堂练习3
"""
3.输入一个数，判断这个数是否同时能被 3 和 5 整除
  例如：
  15 / 3 = 5 ...... 0
  15 / 5 = 3 ...... 0
"""
#使用 “如果....那么.... 否则....” 句式改写
num = int(input("num?"))
#如果输入一个数同时能被 3 和 5 整除，那么输出可以；
if num % 3 == 0 and num % 5 == 0:
    print("可以")
#否则输出不可以
else:
    print("不可以")


