if day == 1:
    print("可以")

#如果星期数不为1，那么就不可以穿新衣
if day != 1:
    print("不可以")

###做法二
    
#如果....那么.... 否则....
#如果星期数为1，那么就可以穿新衣
if day == 1:
    print("可以")
#否则就不可以穿新衣
else: 
    print("不可以")

